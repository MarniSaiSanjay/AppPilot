from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from tempfile import TemporaryDirectory
from unittest.mock import Mock, patch

from apppilot import email_render, report_storage


def test_saves_email_equivalent_markdown_under_test_name_and_date() -> None:
    report = Mock()
    report.to_email_report.return_value = email_render.EmailReport(
        suite_name="Deeplink",
        total=1,
        passed=1,
        failed=0,
        summary_segments=("Installed: 1/1 passed",),
        columns=("S.No", "Test ID", "Result"),
        rows=(
            (
                email_render.Cell(text="1"),
                email_render.Cell(text="TC001", nowrap=True),
                email_render.Cell(status=True, center=True),
            ),
        ),
        details=(
            email_render.DetailCard(
                title="TC001",
                passed=True,
                badge="Attempt 1",
                meta_label="Expected",
                meta_value="App opens",
                attempts=(
                    email_render.DetailAttempt(
                        label="Attempt 1", ok=True, text="matched"
                    ),
                ),
            ),
        ),
        body_text="TC001  PASS",
    )

    with TemporaryDirectory() as temporary:
        with patch.object(report_storage, "_REPORTS_ROOT", Path(temporary)):
            path = report_storage.save_markdown_report(
                report,
                test_name="Deeplink Test Cases",
                env={},
                now=lambda: datetime(2026, 9, 17, 12, 22, 38, tzinfo=timezone.utc),
            )
            assert path == (
                Path(temporary)
                / "Deeplink-Test-Cases"
                / "2026-09-17_12-22-38.md"
            )
            content = path.read_text(encoding="utf-8")
            # Same structure/UX as the HTML email report, rendered as Markdown.
            assert "# AppPilot" in content
            assert "### Deeplink Suite Report" in content
            assert "**Suite result: PASS — 1/1 passed**" in content
            assert "| S.No | Test ID | Result |" in content
            assert "| 1 | TC001 | PASS |" in content
            assert "## Details" in content
            assert "#### TC001 — **PASS** (Attempt 1)" in content
            assert "**Expected:** App opens" in content
            assert "Generated by AppPilot" in content


def test_uses_a_unique_filename_for_reports_created_in_the_same_second() -> None:
    report = Mock()
    report.to_email_report.return_value = email_render.EmailReport(
        suite_name="Deeplink",
        total=0,
        passed=0,
        failed=0,
    )
    now = lambda: datetime(2026, 9, 17, 12, 22, 38, tzinfo=timezone.utc)

    with TemporaryDirectory() as temporary:
        with patch.object(report_storage, "_REPORTS_ROOT", Path(temporary)):
            first = report_storage.save_markdown_report(
                report, test_name="Suite", env={}, now=now
            )
            second = report_storage.save_markdown_report(
                report, test_name="Suite", env={}, now=now
            )

    assert first.name == "2026-09-17_12-22-38.md"
    assert second.name == "2026-09-17_12-22-38-2.md"
